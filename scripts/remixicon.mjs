// Remix Icon, cut down to the icons this site uses.
//   pnpm remixicon            write src/remixicon-subset.css from remixicon.icons + src/**
// The full Remix stylesheet is ~137 KB of glyph rules and blocks the first
// paint; the font is 189 KB. This keeps only the named icons: their rules,
// and a font with only their glyphs, inlined as a data URL (a few KB), so
// there is no font request at all. The @font-face carries a unicode-range,
// so a page that also loads the full Remix stylesheet (the style guide's
// Icons page, from its own head code) still gets every other glyph.
// An icon missing from the list shows nothing until it is added to
// remixicon.icons and this script and pnpm build run again.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { default: subsetFont } = await import('subset-font');
const pkgDir = path.dirname(require.resolve('remixicon/package.json'));
const css = fs.readFileSync(path.join(pkgDir, 'fonts/remixicon.css'), 'utf8');
const woff2 = fs.readFileSync(path.join(pkgDir, 'fonts/remixicon.woff2'));
const version = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;

const names = new Set();
const listFile = path.join(root, 'remixicon.icons');
for (const line of fs.readFileSync(listFile, 'utf8').split('\n')) {
  const n = line.replace(/#.*/, '').trim();
  if (n) names.add(n);
}
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).forEach((e) => {
  const p = path.join(d, e.name);
  if (e.isDirectory()) walk(p);
  else if (/\.(ts|js|html)$/.test(e.name)) for (const m of fs.readFileSync(p, 'utf8').matchAll(/\bri-[a-z0-9]+(?:-[a-z0-9]+)*/g)) names.add(m[0]);
});
walk(path.join(root, 'src'));

const rules = [];
const points = [];
for (const name of [...names].sort()) {
  const m = css.match(new RegExp(`\\.${name}:before\\s*\\{\\s*content:\\s*"\\\\([0-9a-f]+)";?\\s*\\}`));
  if (!m) continue;
  rules.push(`.${name}:before { content: "\\${m[1]}"; }`);
  points.push(parseInt(m[1], 16));
}
if (!points.length) { console.error('remixicon: no known icon names found.'); process.exit(1); }
const font = await subsetFont(woff2, String.fromCodePoint(...points), { targetFormat: 'woff2', keepFeatures: [], noLayoutClosure: true });
const range = points.map((p) => 'U+' + p.toString(16).toUpperCase()).join(', ');
const base = css.match(/\[class\^="ri-"\][^{]*\{[^}]*\}/)?.[0] ?? '[class^="ri-"], [class*=" ri-"] { font-family: "remixicon" !important; font-style: normal; -webkit-font-smoothing: antialiased; -moz-osx-font-smoothing: grayscale; }';
const out = `/* GENERATED by \`pnpm remixicon\` (scripts/remixicon.mjs): do not edit.
   repo-css: third-party — Remix Icon ${version} (Remix Icon License 1.0), only
   the ${rules.length} icons in remixicon.icons and src/. */
@font-face {
  font-family: "remixicon";
  src: url("data:font/woff2;base64,${font.toString('base64')}") format("woff2");
  font-display: block;
  unicode-range: ${range};
}
${base}
${rules.join('\n')}
`;
fs.writeFileSync(path.join(root, 'src/remixicon-subset.css'), out);
console.log(`remixicon ${version}: ${rules.length} icons, font ${Math.round(font.length / 1024)} KB → src/remixicon-subset.css (${Math.round(out.length / 1024)} KB). Run pnpm build.`);
